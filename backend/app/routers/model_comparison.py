"""Router for serving verified ML model comparison artifacts to frontend dashboard."""

from __future__ import annotations

import json
import logging
import os
from pathlib import Path
from typing import Any, Dict

from fastapi import APIRouter, HTTPException

router = APIRouter()
logger = logging.getLogger(__name__)

# Anchored to repo root
_REPO_ROOT = Path(__file__).resolve().parent.parent.parent.parent
_EVAL_FILE = _REPO_ROOT / "ml" / "reports" / "false_positive_reduction" / "evaluation_results.json"
_THRESHOLDS_FILE = _REPO_ROOT / "ml" / "reports" / "false_positive_reduction" / "selected_thresholds.json"


@router.get("/comparison")
async def get_model_comparison() -> Dict[str, Any]:
    """Retrieve verified evaluation metrics, confusion matrices, and threshold trade-offs.

    Loads actual held-out test split evaluation artifacts generated by the
    false-positive reduction optimization pipeline.
    """
    if not _EVAL_FILE.exists():
        logger.error(f"Model evaluation artifact not found at: {_EVAL_FILE}")
        raise HTTPException(
            status_code=503,
            detail="Model evaluation artifacts are not available on this server.",
        )

    try:
        with open(_EVAL_FILE, "r", encoding="utf-8") as f:
            eval_data = json.load(f)
    except Exception as exc:
        logger.error(f"Failed to read evaluation results: {exc}")
        raise HTTPException(status_code=500, detail="Failed to load model evaluation data.")

    thresholds_data = {}
    if _THRESHOLDS_FILE.exists():
        try:
            with open(_THRESHOLDS_FILE, "r", encoding="utf-8") as f:
                thresholds_data = json.load(f)
        except Exception as exc:
            logger.warning(f"Could not read thresholds file: {exc}")

    return {
        "production_default": "xgboost_improved",
        "models": [
            {
                "id": "xgboost_improved",
                "name": "Improved XGBoost",
                "is_production": True,
                "description": "Production default model featuring 72 kinematic and cyclic features, calibrated Platt scaling, and tuned false-positive suppression.",
            },
            {
                "id": "random_forest",
                "name": "Random Forest",
                "is_production": False,
                "description": "Ensemble of 100 balanced decision trees trained on the identical 72-feature schema.",
            },
            {
                "id": "lightgbm",
                "name": "LightGBM",
                "is_production": False,
                "description": "Gradient-boosted decision tree family utilizing histogram-based splits and gradient weighting.",
            },
        ],
        "horizons": ["120s", "360s", "600s", "840s"],
        "test_evaluations": eval_data.get("test_evaluations", {}),
        "validation_evaluations": eval_data.get("validation_evaluations", {}),
        "selected_thresholds": thresholds_data.get("models", {}),
        "dataset_info": {
            "evaluation_split": "Chronological Held-Out Test Cohort (Zero Trajectory Leakage)",
            "sample_counts": {
                "120s": 76022,
                "360s": 46721,
                "600s": 29104,
                "840s": 16697,
            },
            "target_definition": "Movement window deviating >= 3.0 sigma from expanding personal mobility baseline",
            "feature_count": 72,
            "disclaimer": "Derived kinematic outliers are mathematical personalized deviations, NOT clinically confirmed wandering, cognitive impairment, or medical emergency diagnoses.",
        },
    }
